function interpolate(template, values = {}) {
  return String(template).replace(/\{(\w+)\}/g, (match, key) => (
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match
  ));
}

const I18nContext = createContext({
  language: 'de',
  setLanguage: () => {},
  t: key => key,
});

function initialLanguage() {
  try {
    const local = window.localStorage.getItem('language');
    if (local === 'de' || local === 'en') return local;
  } catch {}
  return typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('en') ? 'en' : 'de';
}

export function I18nProvider({ children }) {
  const [language, setLanguageState] = useState(initialLanguage);

  useEffect(() => {
    let active = true;
    async function loadPersistedLanguage() {
      try {
        const stored = await window.electronAPI?.appStateGet?.('language');
        if (active && (stored === 'de' || stored === 'en')) setLanguageState(stored);
      } catch {}
    }
    loadPersistedLanguage();
    return () => { active = false; };
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const setLanguage = useCallback((nextLanguage) => {
    if (nextLanguage !== 'de' && nextLanguage !== 'en') return;
    setLanguageState(nextLanguage);
    try { window.localStorage.setItem('language', nextLanguage); } catch {}
    window.electronAPI?.appStateSet?.('language', nextLanguage);
  }, []);

  const t = useCallback((key, values) => {
    const template = language === 'en' ? (EN[key] || key) : key;
    return interpolate(template, values);
  }, [language]);

  const value = useMemo(() => ({ language, setLanguage, t }), [language, setLanguage, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}

export function translateAgentActivity(t, text) {
  const value = String(text || '');
  const patterns = [
    [/^Arbeitet an:\s*([\s\S]+)$/i, 'Arbeitet an: {task}', 'task'],
    [/^Bearbeitet die Übergabe:\s*([\s\S]+)$/i, 'Bearbeitet die Übergabe: {task}', 'task'],
    [/^Prüft den Abschluss für:\s*([\s\S]+)$/i, 'Prüft den Abschluss für: {task}', 'task'],
    [/^Setzt die Aufgabe mit deiner Antwort fort:\s*([\s\S]+)$/i, 'Setzt die Aufgabe mit deiner Antwort fort: {task}', 'task'],
    [/^Befehl läuft:\s*([\s\S]+)$/i, 'Befehl läuft: {command}', 'command'],
    [/^Werkzeug läuft:\s*([\s\S]+)$/i, 'Werkzeug läuft: {tool}', 'tool'],
    [/^Befehl mit Exit-Code\s+([^\s]+)\s+beendet\.$/i, 'Befehl mit Exit-Code {code} beendet.', 'code'],
  ];
  for (const [pattern, key, variable] of patterns) {
    const match = value.match(pattern);
    if (match) return t(key, { [variable]: match[1] });
  }
  return t(value);
}
